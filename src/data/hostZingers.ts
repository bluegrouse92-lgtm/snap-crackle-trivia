export function pickZinger(): string {
  return HOST_ZINGERS[Math.floor(Math.random() * HOST_ZINGERS.length)];
}

export function pickMultiplayerDig(winner: string, loser: string): string {
  const line = MULTIPLAYER_DUGS[Math.floor(Math.random() * MULTIPLAYER_DUGS.length)];
  return line.replaceAll('{winner}', winner).replaceAll('{loser}', loser);
}
